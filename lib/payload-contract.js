/**
 * Single owner of the pinned runtime-payload contract.
 *
 * The payload is the byte-preserving upstream snapshot that every skill,
 * command, agent role, and Python gate executes from. Its identity, its
 * inventory pins, its runtime Python requirements, and the include/exclude
 * declarations used by the builder are all declared exactly once here so the
 * builder, checker, install verifier, and payload tests cannot drift apart.
 *
 * This module is shipped with the plugin and is deliberately pure data plus
 * pure functions: no `node:fs`, no environment reads, no I/O. Consumers that
 * need to touch the filesystem (the tools in `tools/`) own that I/O and call
 * these declarations.
 *
 * To adopt a legitimate upstream bump: update `UPSTREAM` and
 * `PAYLOAD_SNAPSHOT` here (and `BY_TOP_LEVEL` / `REFERENCE_INDEX` when the
 * content changes), then regenerate the payload with
 * `node tools/build-payload.mjs`.
 *
 * @module payload-contract
 */

