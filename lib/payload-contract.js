const LOCALIZED_README = /^README\.[A-Za-z-]+\.md$/u

const EXCLUSION_REASONS = new Map(EXCLUDED_ENTRIES.map((entry) => [entry.path, entry.reason]))

/** Frozen `path -> reason` view of {@link EXCLUDED_ENTRIES}. */
const EXCLUSIONS_BY_PATH = Object.freeze(Object.fromEntries(EXCLUSION_REASONS))

/** Explicit exclusion reason for one top-level path, or `undefined`. */
export function exclusionReason(path) {
  return EXCLUSION_REASONS.get(path)
}

/** Reason attached to a localized `README.<locale>.md`, or `null`. */
export function localizedReadmeReason(path) {
  if (!LOCALIZED_README.test(path)) return null
  return 'localized README excluded; only the English README.md is bundled'
}

/** Parse a requirements file into trimmed, non-comment requirement lines. */
export function parseRequirementLines(text) {
  return String(text)
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith('#'))
}

/** Human-readable byte count (`1.0 MB`), shared by the tools' reports. */
export function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`
}

