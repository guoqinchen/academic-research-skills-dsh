/** Exclusion reason for one payload-relative file path, or undefined. */
export function distributionFileExclusionReason(path) {
  for (const entry of DISTRIBUTION_EXCLUDED_FILES) {
    if (entry.path === path) return entry.reason
  }
  return undefined
}

